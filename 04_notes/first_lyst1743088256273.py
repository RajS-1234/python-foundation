# tuple is a class
# tuple is a type
# tuple is an iterable
# tuple is a sequence
# tuple elements are indexed
# tuple is immutable
# tuple can contain values of different types


# set is a class
# set is a type
# set is an iterable
# set is not a sequence
# set has no concept of indexing
# set doesn't support slicing operator
# set cannot have duplicate values
# set can have values of different types but not list and set
# set is mutable